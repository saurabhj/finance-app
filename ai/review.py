"""Runs AI reviews: builds the snapshot, calls Claude with structured output,
stores the review and its recommendations, and emails it."""
import json
import logging
from pathlib import Path

import anthropic
import markdown as md
from django.conf import settings
from django.core.mail import EmailMultiAlternatives
from django.db import transaction

from core.models import Instrument, Recommendation, Review
from core.templatetags.money import inr

from . import context
from .schemas import ANSWER_SCHEMA, CADENCE_INSTRUCTIONS, REVIEW_SCHEMA

log = logging.getLogger(__name__)
SYSTEM_PROMPT = (Path(__file__).parent / "prompts" / "system_ymoyl.md").read_text()
DISCLAIMER = ("_Generated by Claude from your app's data. Not licensed financial advice: "
              "you decide and execute every action yourselves._")
EFFORT = {"weekly": "medium", "monthly": "high", "adhoc": "medium"}


class ReviewError(Exception):
    pass


def model_for(cadence):
    return settings.AI_MODEL_LIGHT if cadence == "weekly" else settings.AI_MODEL_DEEP


def user_message(cadence, ctx, question=None):
    head = f"Question from the family: {question}" if question else CADENCE_INSTRUCTIONS[cadence]
    snapshot = json.dumps(ctx, indent=1, sort_keys=True, default=str)
    return f"{head}\n\n<finance_snapshot>\n{snapshot}\n</finance_snapshot>"


def call_claude(model, content, schema, effort, client=None, system=None, max_tokens=64000):
    """One structured-output call. `content` is a string or a list of content blocks.
    Returns (parsed_json, usage_dict, served_model)."""
    if client is None:
        import os
        if not (os.environ.get("ANTHROPIC_API_KEY") or os.environ.get("ANTHROPIC_AUTH_TOKEN")):
            raise ReviewError("Anthropic API key missing: set ANTHROPIC_API_KEY in .env and restart the app.")
        client = anthropic.Anthropic()
    kwargs = dict(
        model=model,
        max_tokens=max_tokens,
        system=[{"type": "text", "text": system or SYSTEM_PROMPT, "cache_control": {"type": "ephemeral"}}],
        thinking={"type": "adaptive"},
        output_config={"effort": effort, "format": {"type": "json_schema", "schema": schema}},
        messages=[{"role": "user", "content": content}],
    )
    try:
        if "haiku" in model:  # Haiku has no server-side refusal fallback
            stream_ctx = client.messages.stream(**kwargs)
        else:
            # On a safety decline, the API retries on a suitable fallback model instead of failing.
            stream_ctx = client.beta.messages.stream(**kwargs, betas=["server-side-fallback-2026-07-01"],
                                                     fallbacks="default")
        with stream_ctx as stream:
            msg = stream.get_final_message()
    except anthropic.AuthenticationError as e:
        raise ReviewError("Anthropic API key missing or invalid: set ANTHROPIC_API_KEY in .env") from e
    except anthropic.RateLimitError as e:
        raise ReviewError("Anthropic rate limit hit; try again in a few minutes.") from e
    except anthropic.APIStatusError as e:
        raise ReviewError(f"Anthropic API error {e.status_code}: {e.message}") from e
    except anthropic.APIConnectionError as e:
        raise ReviewError("Couldn't reach the Anthropic API (network).") from e

    if msg.stop_reason == "refusal":
        detail = getattr(msg.stop_details, "explanation", "") if msg.stop_details else ""
        raise ReviewError(f"The model declined this request. {detail}".strip())
    if msg.stop_reason == "max_tokens":
        raise ReviewError("The review was cut off (max_tokens). Try again.")
    text_out = next((b.text for b in msg.content if b.type == "text"), None)
    if not text_out:
        raise ReviewError("The model returned no text.")
    usage = {k: getattr(msg.usage, k, None) for k in
             ("input_tokens", "output_tokens", "cache_read_input_tokens", "cache_creation_input_tokens")}
    return json.loads(text_out), usage, msg.model


def start_review(cadence, question=""):
    return Review.objects.create(cadence=cadence, model=model_for(cadence), input_json={},
                                 status="running", question=question)


def run_review(cadence, review=None, send_email=True, client=None):
    review = review or start_review(cadence)
    try:
        ctx = context.build(cadence)
        review.input_json = ctx
        review.save(update_fields=["input_json"])
        out, usage, served = call_claude(review.model, user_message(cadence, ctx), REVIEW_SCHEMA,
                                         EFFORT[cadence], client=client)
    except (ReviewError, ValueError) as e:
        review.status, review.error = "failed", str(e)
        review.save(update_fields=["status", "error"])
        raise ReviewError(str(e)) from e
    _store(review, out, usage, served, ctx)
    if send_email:
        try:
            send_review_email(review)
        except Exception as e:  # email trouble shouldn't lose the review
            log.exception("Review email failed")
            review.error = f"Saved, but email failed: {e}"
            review.save(update_fields=["error"])
    return review


def ask(question, client=None):
    review = start_review("adhoc", question=question)
    try:
        ctx = context.build("adhoc", fetch_history=False)
        review.input_json = ctx
        out, usage, served = call_claude(review.model, user_message("adhoc", ctx, question), ANSWER_SCHEMA,
                                         EFFORT["adhoc"], client=client)
    except (ReviewError, ValueError) as e:
        review.status, review.error = "failed", str(e)
        review.save()
        raise ReviewError(str(e)) from e
    gaps = "".join(f"\n- {g}" for g in out.get("data_gaps", []))
    review.output_json, review.usage, review.model, review.status = out, usage, served, "done"
    review.output_markdown = out["answer"] + (f"\n\n**Data gaps:**{gaps}" if gaps else "") + f"\n\n{DISCLAIMER}"
    review.save()
    return review


@transaction.atomic
def _store(review, out, usage, served, ctx):
    names = {h["instrument_id"]: h["name"] for h in ctx["holdings"]["self_managed"]}
    valid = set(Instrument.objects.filter(id__in=names).values_list("id", flat=True))
    for rec in out.get("recommendations", []):
        Recommendation.objects.create(
            review=review, verdict=rec["verdict"], title=rec["title"][:200], rationale=rec["rationale"],
            amount=rec["amount"] or None, urgency=rec["urgency"],
            instrument_id=rec["instrument_id"] if rec["instrument_id"] in valid else None,
        )
    for hv in out.get("holding_verdicts", []):
        if hv["instrument_id"] not in valid:
            continue
        is_hold = hv["verdict"] == "hold"
        Recommendation.objects.create(
            review=review, instrument_id=hv["instrument_id"], verdict=hv["verdict"],
            title=f"{hv['verdict'].title()}: {names[hv['instrument_id']]}"[:200], rationale=hv["rationale"],
            amount=hv["amount"] or None,
            status=Recommendation.Status.DONE if is_hold else Recommendation.Status.OPEN,
            status_note="No action needed" if is_hold else "",
        )
    review.output_json, review.usage, review.model, review.status = out, usage, served, "done"
    review.output_markdown = render_markdown(out, names)
    review.save()


def render_markdown(out, names):
    lines = [f"## {out['headline']}", "", out["summary"], "", "### Progress to financial independence", "",
             out["fi_progress"], ""]
    if out["recommendations"]:
        lines += ["### What to do", ""]
        for i, r in enumerate(out["recommendations"], 1):
            amt = f" · {inr(r['amount'])}" if r["amount"] else ""
            lines.append(f"{i}. **{r['title']}** ({r['verdict']}, {r['urgency']} urgency{amt})  \n   {r['rationale']}")
        lines.append("")
    else:
        lines += ["### What to do", "", "Nothing needs doing right now.", ""]
    if out["holding_verdicts"]:
        lines += ["### Self-managed holdings", "", "| Holding | Verdict | Amount | Why |", "|---|---|---|---|"]
        for h in out["holding_verdicts"]:
            why = h["rationale"].replace("|", "/").replace("\n", " ")
            amt = inr(h["amount"]) if h["amount"] else "—"
            lines.append(f"| {names.get(h['instrument_id'], h['instrument_id'])} | **{h['verdict'].title()}** | {amt} | {why} |")
        lines.append("")
    if out["advisor_strategy_notes"]:
        lines += ["### Advisor strategies", ""]
        lines += [f"- **{a['advisor']}**{' ⚠️' if a['flag'] else ''}: {a['assessment']}" for a in out["advisor_strategy_notes"]]
        lines.append("")
    for title, key in (("Risks", "risks"), ("Data gaps", "data_gaps"), ("Questions for you", "questions_for_you")):
        if out[key]:
            lines += [f"### {title}", ""] + [f"- {x}" for x in out[key]] + [""]
    lines.append(DISCLAIMER)
    return "\n".join(lines)


def render_html(markdown_text):
    return md.markdown(markdown_text, extensions=["tables", "sane_lists"])


def send_review_email(review):
    recipients = settings.REPORT_RECIPIENTS
    if not recipients:
        return False
    headline = (review.output_json or {}).get("headline", "")
    subject = f"{review.get_cadence_display()} finance review: {headline}"[:180]
    link = f"{settings.APP_BASE_URL}/reviews/{review.id}/"
    text = f"{review.output_markdown}\n\nOpen in the app: {link}"
    html = render_html(review.output_markdown) + f'<p><a href="{link}">Open in the app</a> to mark actions done or dismissed.</p>'
    msg = EmailMultiAlternatives(subject, text, settings.DEFAULT_FROM_EMAIL, recipients)
    msg.attach_alternative(html, "text/html")
    msg.send()
    return True
